def check_one(kind, path):
    """检查单个宿主文件。返回 dict(status, detail)。

    status ∈ {"installed", "legacy", "drifted", "missing_host_file", "missing"}
    """
    if not os.path.isfile(path):
        return {"status": "missing_host_file", "detail": "宿主文件不存在：%s" % path}
    txt = io.open(path, encoding="utf-8").read()
    expected = BLOCKS[kind]

    if MARK_BEGIN in txt and MARK_END in txt:
        # 从 MARK_BEGIN **所在行的行首**截取（保留首行可能存在的前导缩进）
        mark_pos = txt.index(MARK_BEGIN)
        begin = txt.rfind("\n", 0, mark_pos) + 1
        end = txt.index(MARK_END) + len(MARK_END)
        actual_block = txt[begin:end]
        # 规范化：仅去行尾空白 + 首尾空行（宿主可能被编辑器改过行尾）。
        # 不做「共同缩进剥离」——真源块自带函数体内缩进，剥掉会掩盖
        # 双层缩进等真实漂移。
        def norm(s):
            return "\n".join(x.rstrip() for x in s.strip().splitlines())
        if norm(actual_block) == norm(expected):
            return {"status": "installed", "detail": "marker 块与真源一致"}
        return {"status": "drifted",
                "detail": "marker 块内容漂移（宿主被手改或真源已升级），需 --install 重装"}

    if LEGACY_MARKERS[kind] in txt and "self_gate.py" in txt:
        return {"status": "legacy",
                "detail": "第5轮手写块（无 marker）——功能等价，建议 --install 迁移为可校验形态"}

    if "self_gate.py" in txt:
        return {"status": "legacy",
                "detail": "检测到未识别形态的 self_gate 调用，建议 --install 归一"}

    return {"status": "missing", "detail": "未接入 self_gate"}


# ── 宿主缺陷修复块（S-E76）：独立于门禁块的第二类 marker ────────────
def _hostfix_code_state(txt):
    """宿主里「脆弱写法」与「兼容写法」的实际分布。返回 (vuln, fixed)。

    只认**赋值语句行**，不认注释行 —— 宿主注释里出现 PIPESTATUS[0]
    是历史说明（含在修复块的说明文字里），不是可执行缺陷。
    按子串匹配会把注释误判为缺陷（实测自测暴露的误报来源）。

    返回 (vuln, fixed, rc_needed, rc_ok)：
      vuln     —— 脆弱赋值（PUSH_RC=${PIPESTATUS[0]}）处数
      fixed    —— 兼容赋值（PUSH_RC=$_triz_push_rc）处数
      rc_needed —— S-E79 判据是否适用（宿主含 `|| true` 脆弱调用，
                   或已有 SCRIPT_RC 改写痕迹）；两皆无 → False（不适用，
                   不纳入判定，否则会误伤「只有 PIPESTATUS 缺陷」的宿主）
      rc_ok    —— S-E79 修复形态是否完整（透传 + 初始化 + 结尾 exit）
    """
    vuln = len(re.findall(r"(?m)^[ \t]*PUSH_RC=.*\$\{PIPESTATUS\[0\]\}", txt))
    fixed = len(re.findall(r"(?m)^[ \t]*PUSH_RC=\$_triz_push_rc", txt))
    rc_vuln = len(_HOSTFIX_RC_PATTERNS[0][0].findall(txt)) + \
        len(_HOSTFIX_RC_PATTERNS[1][0].findall(txt))
    has_rc_code = False
    for line in txt.splitlines():
        s = line.strip()
        if s and not s.startswith("#") and "SCRIPT_RC" in s:
            has_rc_code = True
            break
    rc_needed = (rc_vuln > 0) or has_rc_code
    rc_ok = (
        bool(re.search(r"(?m)^[ \t]*inspect_pkg \"\$pkg\"( batch)? \|\| SCRIPT_RC=1", txt))
        and bool(re.search(
            r"(?m)^[ \t]*inspect_pkg \"\$TARGET\" \|\| SCRIPT_RC=\$\?", txt))
        and bool(re.search(r"(?m)^exit \$SCRIPT_RC[ \t]*$", txt))
    )
    # S-E80：宿主有 --all 循环（SCRIPT_RC=1 形态）即需要 batch 跳过语义；
    # 修复形态 = 签名 ctx 注入 + 循环调用带 batch + 环境守卫在位。
    ctx_needed = rc_needed
    ctx_ok = (
        bool(re.search(r"(?m)^inspect_pkg\(\) \{\n[ \t]*local ctx=", txt))
        and bool(re.search(r"(?m)^[ \t]*inspect_pkg \"\$pkg\" batch \|\| SCRIPT_RC=1", txt))
        and bool(re.search(r"(?m)^[ \t]*if \[ \"\$ctx\" = \"batch\" \]; then", txt))
    )
    return vuln, fixed, rc_needed, rc_ok, ctx_needed, ctx_ok


def check_hostfix_one(kind, path):
    """检查宿主缺陷修复块是否就位。返回 dict(status, detail)。

    status ∈ {"installed", "not_needed", "missing", "drifted", "regressed"}
      · not_needed —— 该宿主文件不含该缺陷（不适用）
      · missing    —— 存在缺陷但修复块未注入 → 判失败
      · drifted    —— 修复块被手改 → 判失败
      · regressed  —— 修复块在位但**代码被回滚** → 判失败（假绿防线）
    """
    if kind not in HOSTFIX_BLOCKS:
        return {"status": "not_needed", "detail": "该宿主文件无此缺陷"}
    if not os.path.isfile(path):
        return {"status": "missing", "detail": "宿主文件不存在"}
    txt = io.open(path, encoding="utf-8").read()
    expected = HOSTFIX_BLOCKS[kind]
    vuln, fixed, rc_needed, rc_ok, ctx_needed, ctx_ok = _hostfix_code_state(txt)

    if MARK_BEGIN_FIX in txt and MARK_END_FIX in txt:
        # 提取所有修复块，逐个比对，任一与真源一致即视为块在位
        block_ok = False
        for blk in extract_marker_blocks(txt, MARK_BEGIN_FIX, MARK_END_FIX):
            if norm_block(blk) == norm_block(expected):
                block_ok = True
                break
        if not block_ok:
            return {"status": "drifted", "detail": "修复块内容漂移，需 --install 重装"}
        # 块在位**不等于**缺陷已修 —— 必须同时校验代码实际形态，
        # 否则人工把代码改回 ${PIPESTATUS[0]} 仍会判通过（假绿）。
        if vuln > 0:
            return {"status": "regressed",
                    "detail": "修复块在位但脆弱写法回归（%d 处 PUSH_RC=${PIPESTATUS[0]}）"
                              "→ 推送失败检测失效" % vuln}
        if fixed == 0:
            return {"status": "regressed",
                    "detail": "修复块在位但兼容写法已消失 → 推送失败检测失效"}
        # S-E79：仅当宿主确有 `|| true` 脆弱调用（或已有改写痕迹）时才判定。
        # 一刀切会误伤「只有 PIPESTATUS 缺陷」的宿主形态（实测自测暴露）。
        if rc_needed and not rc_ok:
            return {"status": "regressed",
                    "detail": "S-E79 修复回归（SCRIPT_RC 透传或 exit 缺失）"
                              "→ 推送失败退出码被主流程吞掉（恒 RC=0）"}
        # S-E80：同型适用性判断——有 --all 循环才需要 batch 跳过语义。
        if ctx_needed and not ctx_ok:
            return {"status": "regressed",
                    "detail": "S-E80 修复回归（batch 跳过语义缺失）"
                              "→ --all 环境性跳过被计为失败（成功假红）"}
        return {"status": "installed",
                "detail": "修复块已就位（兼容写法 %d 处%s%s）"
                          % (fixed,
                             " + SCRIPT_RC 透传" if rc_ok else "",
                             " + batch 跳过" if ctx_ok else "")}

    # 无修复块：按代码形态判定
    if vuln > 0:
        return {"status": "missing",
                "detail": "宿主仍用 ${PIPESTATUS[0]}（zsh 下未定义）→ 推送失败检测失效"}
    if fixed > 0 or (rc_needed and not rc_ok) or (ctx_needed and not ctx_ok):
        # 代码已改写但块缺失 → 仍判 missing：块是「代码是否回归」的检出锚点，
        # 缺块则回归无人发现（此前误判 not_needed，导致 install 幂等路径
        # 永远补不上块 —— 实测自测暴露）。
        return {"status": "missing",
                "detail": "修复形态不完整或修复块缺失（缺回归检出锚点）"}
    return {"status": "not_needed", "detail": "宿主文件无该缺陷"}


def extract_marker_blocks(txt, begin_marker=None, end_marker=None):
    """提取指定 marker 对包裹的所有块。返回 [block_text, ...]。

    边界规则：块的**起止行必须整行是 marker**（行首无其它字符）。
    若 marker 前一行有残留文本（如 "set" 紧贴 marker），说明上一次注入
    破坏了宿主结构——此时**不**把残留文本算进块内，并额外标记，
    由调用方识别（实测自测暴露：注入点落在 "set" 与 "-uo pipefail" 之间）。
    """
    begin_marker = begin_marker or MARK_BEGIN
    end_marker = end_marker or MARK_END
    out = []
    pos = 0
    while True:
        b = txt.find(begin_marker, pos)
        if b == -1:
            break
        e = txt.find(end_marker, b)
        if e == -1:
            break
        e += len(end_marker)
        line_start = txt.rfind("\n", 0, b) + 1
        # 关键：块起点必须是**整行** marker —— 行首到 marker 之间若有
        # 其它字符说明结构已被破坏，截断到 marker 处以免把残留算进块。
        if txt[line_start:b].strip():
            line_start = b
        out.append(txt[line_start:e])
        pos = e
    return out



def norm_block(s):
    """规范化块内容：仅去行尾空白 + 首尾空行（与 check_one 同口径）。"""
    return "\n".join(x.rstrip() for x in s.strip().splitlines())



def verify_host(host_root, verbose=False):
    """宿主接入状态唯一判据（self_gate.py 反向 import 本函数）。

    返回 (ok: bool, results: dict)。
    legacy 视作**已接入**（功能等价），drifted / missing 判失败。
    宿主缺陷修复块（S-E76）缺失同样判失败——否则推送失败检测仍是假绿。
    """
    paths = host_paths(host_root)
    results = {k: check_one(k, p) for k, p in paths.items()}
    hostfix = {k: check_hostfix_one(k, p) for k, p in paths.items()}
    bad = {k: v for k, v in results.items()
           if v["status"] in ("missing", "missing_host_file", "drifted")}
    bad.update({("hostfix:" + k): v for k, v in hostfix.items()
                if v["status"] in ("missing", "drifted", "regressed")})
    if verbose:
        for k, v in sorted(results.items()):
            flag = {"installed": "✅", "legacy": "✅", "drifted": "❌",
                    "missing": "❌", "missing_host_file": "❌"}[v["status"]]
            print("  %s %-14s %-12s %s" % (flag, k, v["status"], v["detail"]))
        for k, v in sorted(hostfix.items()):
            flag = {"installed": "✅", "not_needed": "➖", "drifted": "❌",
                    "missing": "❌", "regressed": "❌"}[v["status"]]
            print("  %s %-14s %-12s %s" % (flag, "hostfix:" + k, v["status"], v["detail"]))
    return (not bad), results



def _rewrite_push_rc(txt):
    """把「if 管道; then : fi + PUSH_RC=${PIPESTATUS[0]}」改写为
    「if 管道; then _triz_push_rc=0; else _triz_push_rc=$?; fi + PUSH_RC=$_triz_push_rc」。

    为什么必须改 if 结构（而非只换变量名）：
      zsh 的 `pipestatus` 在 if 条件求值**之后**会被重置 → 只换成
      `${pipestatus[1]}` 在 if 之后仍取到 0（实测）。必须在 if 内部捕获。
      `if 管道; then RC=0; else RC=$?; fi` 不依赖任何 shell 特有数组，
      zsh / bash 通用（配合宿主 set -o pipefail 取管道首命令真实退出码）。

    幂等：**逐结构**判定，而非全局早退（实测缺陷）。
      早先版本在函数开头判断「文件里存在 `_triz_push_rc=` 就不改」——
      但真实宿主有**两处**推送结构：若只有其中一处被回滚成
      `${PIPESTATUS[0]}`，全局早退会让**另一处已修好的**挡住这处的修复，
      re-install 无法自愈（实测自测暴露：「回归后 re-install 自愈」失败）。
      现把幂等下沉到正则层：pattern 要求匹配到脆弱赋值才命中，
      改写后的结构不再匹配 `:` 那一行 → 天然幂等且可局部自愈。

    注释处理（实测发现）：`fi` 与 `PUSH_RC` 之间夹的注释行若仍在讲
    「用 PIPESTATUS[0] 取退出码」，改写后就成了**过时且误导**的文档
    （真实宿主第 261 行正是如此）。因此改写时同步把该注释替换为
    描述新写法的说明 —— 注释错比代码错更隐蔽。
    """
    # 模式：if <管道>; then\n <body>\n <缩进>fi\n [可选注释行]\n <缩进>PUSH_RC=<赋值>
    # body 有两种形态，都要能匹配：
    #   脆弱形态：`:`（原始写法）
    #   已修形态：`_triz_push_rc=0 / else / _triz_push_rc=$?`（本次改写产物）
    # 两种都归一输出为「已修形态」→ 天然幂等，且**局部**可自愈
    # （一处回滚不影响另一处的修复，实测自测暴露：全局早退会导致不自愈）。
    # 缩进不强制一致（宿主里 `:` 与 `fi` 的缩进可能不同）——
    # 各行缩进独立捕获，以 `fi` 的缩进作为生成块的基准。
    # fi 与 PUSH_RC 之间**可能夹注释行**（真实宿主就有），必须容忍。
    pat = re.compile(
        r"(?m)^([ \t]*)if ([^\n]*\|[^\n]*); then\n"
        r"(?P<body>[ \t]*:[ \t]*\n"
        r"|[ \t]*_triz_push_rc=0[ \t]*\n"
        r"[ \t]*else[ \t]*\n"
        r"[ \t]*_triz_push_rc=\$\?[ \t]*\n)"
        r"([ \t]*)fi\n"
        r"((?:[ \t]*#[^\n]*\n)*)"
        r"([ \t]*)PUSH_RC=(?:\$\{PIPESTATUS\[0\]\}|\$_triz_push_rc)")
    def _fix_comments(comments, indent):
        """把过时的 PIPESTATUS 说明注释改写为兼容写法的说明。

        只处理**本结构 fi 与赋值之间**的注释——修复块自身的说明注释
        位于别处，不会被波及（否则会把「原写法 PUSH_RC=${PIPESTATUS[0]}」
        这句历史说明也改掉，反而丢失溯源信息）。
        """
        if not comments:
            return comments
        out = []
        for line in comments.splitlines(True):
            if "PIPESTATUS" in line and line.lstrip().startswith("#"):
                out.append(
                    indent + "# 退出码在管道 if 内部捕获（zsh/bash 通用，不依赖 "
                    "PIPESTATUS 数组）\n")
            else:
                out.append(line)
        return "".join(out)

    def _rep(m):
        ind, pipe, ind_fi, comments, ind_rc = m.group(1, 2, 4, 5, 6)
        comments = _fix_comments(comments, ind_rc)
        return ("%sif %s; then\n"
                "%s  _triz_push_rc=0\n"
                "%selse\n"
                "%s  _triz_push_rc=$?\n"
                "%sfi\n"
                "%s%sPUSH_RC=$_triz_push_rc"
                % (ind, pipe, ind_fi, ind_fi, ind_fi, ind_fi, comments, ind_rc))
    return pat.sub(_rep, txt)


# S-E79：主流程 `inspect_pkg ... || true` 吞掉失败退出码。
# 改写规则（按行替换，两条形态）：
#   `  inspect_pkg "$pkg" || true`     → `  inspect_pkg "$pkg" || SCRIPT_RC=1`
#   `  inspect_pkg "$TARGET" || true`  → `  inspect_pkg "$TARGET" || SCRIPT_RC=$?`
# 为什么两处不同：--all 循环要求**一个包失败不影响其余包遍历**，
#   故只记 1（最终退出码非零即可）；单包模式则透传真实退出码，
#   让调用方能区分失败类型（如 1=推送失败 / 2=用法错）。
# 幂等：SCRIPT_RC 已出现在主流程（非注释行）则整体跳过。
# SCRIPT_RC 需在主流程前初始化（SCRIPT_RC=0），否则 set -u 下未定义中止。
_HOSTFIX_RC_PATTERNS = [
    (re.compile(r"(?m)^([ \t]*)inspect_pkg \"\$pkg\" \|\| true[ \t]*$"),
     lambda m: '%sinspect_pkg "$pkg" || SCRIPT_RC=1' % m.group(1)),
    (re.compile(r"(?m)^([ \t]*)inspect_pkg \"\$TARGET\" \|\| true[ \t]*$"),
     lambda m: '%sinspect_pkg "$TARGET" || SCRIPT_RC=$?' % m.group(1)),
]


def _rewrite_script_rc(txt):
    """把主流程的 `inspect_pkg ... || true` 改写为 SCRIPT_RC 透传。

    幂等：正文（非注释行）已有 `SCRIPT_RC=` 赋值或引用则原样返回。
    注释行不受影响（修复块的说明注释里会出现 SCRIPT_RC 字样）。
    """
    for line in txt.splitlines():
        s = line.strip()
        if s and not s.startswith("#") and "SCRIPT_RC" in s:
            return txt
    out = txt
    for pat, rep in _HOSTFIX_RC_PATTERNS:
        out = pat.sub(rep, out)
    # 在主流程标记前初始化 SCRIPT_RC（set -u 下未定义会中止）
    init = "SCRIPT_RC=0\n"
    anchor = "# ─── 主流程 ───"
    if anchor in out and init not in out:
        out = out.replace(anchor, anchor + "\n" + init, 1)
    return out


# S-E80：--all 循环中白名单包「路径不存在 / 无 .git」触发的 return 1
# 属**环境性跳过**（宿主上包是否装了本来就是环境状态，不是推送失败），
# 但会被 SCRIPT_RC=1 计为失败 → --all 恒 RC=1（成功假红，实测暴露）。
# 修复分两步（保持幂等与最小侵入）：
#   ① inspect_pkg 函数签名加第 2 参数 ctx（环境上下文），两处环境性
#     `return 1` 改为「batch 上下文 → WARN + return 0（SKIP 语义）；
#     其他上下文 → 保持 return 1」（单包显式指定仍报错）。
#   ② --all 循环调用点传入 "batch"。
# 无 remote 跳过原本就 return 0，无需处理。
_HOSTFIX_CTX_PATTERNS = [
    # ① 函数签名：inspect_pkg() { → inspect_pkg() { local ctx...（借函数体首行注入）
    (re.compile(r"(?m)^inspect_pkg\(\) \{\n"),
     "inspect_pkg() {\n  local ctx=\"${2:-single}\"  # S-E80: batch=环境跳过放行\n"),
    # ② 路径不存在：环境状态 → batch 上下文下 SKIP
    (re.compile(
        r"(?m)^([ \t]*)echo \"  ❌ \$pkg 路径不存在: \$pkg_dir\"\n"
        r"([ \t]*)return 1\n"),
     lambda m: ('%secho "  ❌ $pkg 路径不存在: $pkg_dir"\n'
                '%sif [ "$ctx" = "batch" ]; then\n'
                '%s  log "$pkg SKIP reason=no-dir (batch)"\n'
                '%s  return 0   # S-E80: --all 循环中环境性跳过不计失败\n'
                '%sfi\n'
                '%sreturn 1\n') % (m.group(1), m.group(2), m.group(2),
                                   m.group(2), m.group(2), m.group(2))),
    # ③ 无 .git：环境状态 → batch 上下文下 SKIP
    (re.compile(
        r"(?m)^([ \t]*)echo \"  ❌ \$pkg 无\.git\"\n"
        r"([ \t]*)log \"\$pkg FAIL reason=no-git\"\n"
        r"([ \t]*)popd >/dev/null\n"
        r"([ \t]*)return 1\n"),
     lambda m: ('%secho "  ❌ $pkg 无.git"\n'
                '%slog "$pkg FAIL reason=no-git"\n'
                '%spopd >/dev/null\n'
                '%sif [ "$ctx" = "batch" ]; then\n'
                '%s  log "$pkg SKIP reason=no-git (batch)"\n'
                '%s  return 0   # S-E80: --all 循环中环境性跳过不计失败\n'
                '%sfi\n'
                '%sreturn 1\n') % (m.group(1), m.group(2), m.group(3),
                                   m.group(3), m.group(3), m.group(3),
                                   m.group(3), m.group(4))),
    # ④ --all 循环调用点：传入 batch 上下文
    (re.compile(r"(?m)^([ \t]*)inspect_pkg \"\$pkg\" \|\| SCRIPT_RC=1[ \t]*$"),
     lambda m: '%sinspect_pkg "$pkg" batch || SCRIPT_RC=1' % m.group(1)),
]


def _rewrite_batch_skip(txt):
    """S-E80：环境性跳过在 batch 上下文不计失败。

    幂等：正文（非注释行）已有 `local ctx=` 或 `batch ||` 痕迹则原样返回。
    """
    for line in txt.splitlines():
        s = line.strip()
        if s and not s.startswith("#") and ("local ctx=" in s or "batch ||" in s):
            return txt
    out = txt
    for pat, rep in _HOSTFIX_CTX_PATTERNS:
        out = pat.sub(rep, out)
    return out


def _hostfix_injection_pos(txt):
    """定位宿主缺陷修复块的注入位置（字符 offset）。找不到返回 None。

    定位策略（按优先级，**结构优先于注释措辞**）：
      ① 第一个 `PUSH_RC=${PIPESTATUS[0]}` 或 `PUSH_RC=$_triz_push_rc`
         赋值行**所属的** `if ... | ...; then` 管道的行首（向前回溯）
         —— 修复块插在这个 if 之前，语义上「说明本次修复改的是哪段」。
      ② 退化：第一个 `PUSH_RC=` 赋值行的行首（宿主结构改版时）。
      ③ 退化：第一个含 `PIPESTATUS[0]` 的非注释行行首。

    为什么不用注释当锚点（实测缺陷）：
      注释文本会随改写一起变化 → 锚点自毁；且换台机器/换个人改写
      措辞就找不到 → 静默跳过修复（假绿）。结构定位与措辞解耦。
    """
    # ① 回溯到所属的管道 if
    m = re.search(r"(?m)^[ \t]*PUSH_RC=(?:\$\{PIPESTATUS\[0\]\}|\$_triz_push_rc)", txt)
    if m:
        head = txt[:m.start()]
        # 向前找最近的一个「含管道且以 if 开头」的行
        pipe_if = None
        for lm in re.finditer(r"(?m)^([ \t]*)if [^\n]*\|[^\n]*; then\s*$", head):
            pipe_if = lm
        if pipe_if is not None:
            return pipe_if.start()
        # ② 退化：赋值行行首
        return m.start()
    # ③ 退化：任意含 PIPESTATUS[0] 的非注释行
    m2 = re.search(r"(?m)^[ \t]*(?!#)[^\n]*PIPESTATUS\[0\][^\n]*$", txt)
    if m2:
        return m2.start()
    return None


def install_hostfix(host_root, dry_run=False):
    """注入宿主缺陷修复块（S-E76）。**独立于门禁块**，不被其失败阻断。

    门禁块缺失只影响「门禁是否生效」；宿主缺陷（如 zsh PIPESTATUS 假绿）
    影响「推送结果是否被正确判定」——后者更危险，绝不能因为前者缺失而
    一起跳过（实测：pre-commit 缺失导致 install 提前 return 2，
    修复块根本没注入，缺陷原样留在宿主里）。

    注入点定位改为**结构性**（实测缺陷）：
      早先版本靠「注释行文本」当锚点（如 `# PIPESTATUS 需在管道后立即取值…`），
      而同一轮又要改写那段注释 → 锚点自毁，且改写顺序与锚点文本强耦合。
      现改为按**代码结构**定位：找到第一处脆弱赋值所在的 `if 管道` 结构，
      把修复块插到该 `if` 行之前。结构与注释措辞解耦。
    """
    paths = host_paths(host_root)
    changed = []
    for kind, path in paths.items():
        if kind not in HOSTFIX_BLOCKS:
            continue
        if not os.path.isfile(path):
            print("  ⚠️  %-14s 宿主文件不存在，跳过修复块注入" % kind)
            continue
        st = check_hostfix_one(kind, path)
        if st["status"] in ("installed", "not_needed"):
            continue
        txt = io.open(path, encoding="utf-8").read()
        block = HOSTFIX_BLOCKS[kind]

        # 已存在旧修复块（漂移或代码回归）：先移除旧块，再统一注入，
        # 否则产生重复块（幂等检查会因 marker 重复而失败）。
        if MARK_BEGIN_FIX in txt:
            for old in extract_marker_blocks(txt, MARK_BEGIN_FIX, MARK_END_FIX):
                b = txt.index(old)
                e = b + len(old)
                txt = txt[:b].rstrip() + "\n\n" + txt[e:].lstrip("\n")

        # 把脆弱写法替换为兼容用法——**必须改 if 结构**，不只是换变量名：
        #   原：  if git push ... | sed ...; then
        #           :
        #         fi
        #         PUSH_RC=${PIPESTATUS[0]}
        #   新：  if git push ... | sed ...; then
        #           _triz_push_rc=0
        #         else
        #           _triz_push_rc=$?
        #         fi
        #         PUSH_RC=$_triz_push_rc
        # zsh 下只有在 if **内部**才能拿到管道的真实退出码（if 之后
        # pipestatus 已被重置，实测取到 0）。
        # 注意：真实宿主有**两处**脆弱写法（普通推送 + diverged 强制推送），
        # 必须一次全改 —— re.sub 默认替换全部匹配。
        txt = _rewrite_push_rc(txt)

        # S-E79：主流程 `|| true` 吞掉 inspect_pkg 的失败退出码 →
        # 脚本无论推送成败恒以 RC=0 收场（端到端实测暴露）。
        # 同轮修复：改写调用点 + 结尾 exit $SCRIPT_RC。
        # 改写器内部幂等；是否追加 exit 由「真的匹配到 || true 结构」决定
        # —— 对没有该结构的宿主盲目追加，会在 set -u 下引用未初始化的
        # SCRIPT_RC 反而破坏脚本（实测自测暴露）。
        before_rc = txt
        txt = _rewrite_script_rc(txt)
        rc_applied = (txt != before_rc)
        # S-E80：环境性跳过在 batch 上下文不计失败（成功假红修复）
        before_ctx = txt
        txt = _rewrite_batch_skip(txt)
        ctx_applied = (txt != before_ctx)

        # 结构化注入点：第一个脆弱/兼容赋值所在的 `if 管道` 结构之前；
        # 若结构不匹配（宿主改版），退化为第一个 PUSH_RC= 赋值行之前。
        pos = _hostfix_injection_pos(txt)
        if pos is None:
            print("  ⚠️  %-14s 宿主缺陷位置定位失败，跳过（未改坏原文件）" % kind)
            continue

        new_txt = txt[:pos] + block + "\n" + txt[pos:]
        if rc_applied:
            new_txt = new_txt.rstrip("\n") + "\n\nexit $SCRIPT_RC\n"
        fixes = [f for f, on in (("PIPESTATUS 兼容", True),
                                 ("SCRIPT_RC 透传" if rc_applied else None, rc_applied),
                                 ("S-E80 batch 跳过" if ctx_applied else None, ctx_applied)) if on]
        if dry_run:
            print("  🔍 %-14s [dry-run] 将注入宿主缺陷修复块（%d 字节，位置 offset=%d%s）"
                  % (kind, len(block), pos,
                     " + " + " + ".join(fixes[1:]) if len(fixes) > 1 else ""))
            changed.append(kind + ":hostfix")
            continue
        if not os.path.exists(path + ".triz-gate.bak"):
            shutil.copy2(path, path + ".triz-gate.bak")
        io.open(path, "w", encoding="utf-8").write(new_txt)
        print("  ✅ %-14s 宿主缺陷修复块已注入（%s）" % (kind, " + ".join(fixes)))
        changed.append(kind + ":hostfix")
    return 0, changed


def install_host(host_root, dry_run=False):
    """幂等注入。已是 installed 则跳过；legacy/missing 则归一为 marker 块。

    顺序说明：门禁块**先**注入，宿主缺陷修复块**后**注入。
    反序会让门禁块的 fallback 锚点（如 '}'）匹配到修复块内部，
    把门禁块插进修复块中间、截断其注释（实测自测暴露：
    `PUSH_RC=${PIPESTATUS[0]` 被拦腰截断）。
    """
    paths = host_paths(host_root)
    changed = []
    gate_rc = 0
    for kind, path in paths.items():
        if not os.path.isfile(path):
            print("  ❌ %-14s 宿主文件不存在，拒绝创建（避免破坏宿主工具链）：%s"
                  % (kind, path))
            gate_rc = 2
            continue
        st = check_one(kind, path)
        if st["status"] == "installed":
            print("  ✅ %-14s 已是最新 marker 块，跳过" % kind)
            continue
        txt = io.open(path, encoding="utf-8").read()

        # 移除旧块（legacy 手写块 or 漂移的 marker 块），再统一注入
        if st["status"] == "drifted":
            b, e = txt.index(MARK_BEGIN), txt.index(MARK_END) + len(MARK_END)
            txt = txt[:b].rstrip() + "\n\n" + txt[e:].lstrip("\n")
        elif st["status"] == "legacy" and LEGACY_MARKERS[kind] in txt:
            # 第5轮手写块：定位注释起点到其 if 块结束。
            # 用「锚点之前」的边界法：手写块总是紧贴 ANCHORS[kind] 之前。
            anchor = ANCHORS[kind]
            if anchor in txt:
                head = txt[:txt.index(anchor)]
                marker_idx = head.find(LEGACY_MARKERS[kind])
                if marker_idx != -1:
                    # 回退到注释块起点（该行首）
                    line_start = head.rfind("\n", 0, marker_idx) + 1
                    txt = head[:line_start] + txt[txt.index(anchor):]
        anchor = ANCHORS[kind] if ANCHORS[kind] in txt else None
        if anchor is None:
            for cand in FALLBACK_ANCHORS[kind]:
                if cand in txt:
                    anchor = cand
                    break
        if anchor is None:
            print("  ❌ %-14s 主锚点与 fallback 锚点均缺失，拒绝盲插" % kind)
            print("     请把宿主文件的结构点补入 ANCHORS/FALLBACK_ANCHORS 后重试")
            gate_rc = 2
            continue
        # 直接注入真源块，**不做缩进再对齐**：BLOCK_RELEASE_SYNC 自带 2 空格
        # 函数体内缩进，若再按锚点缩进叠加一层会造成双重缩进 → check_one
        # 误判 drifted（实测自测暴露）。bash 不在意块级缩进，原样注入最稳。
        block = BLOCKS[kind]
        new_txt = txt.replace(anchor, block + "\n" + anchor, 1)
        if dry_run:
            print("  🔍 %-14s [dry-run] 将注入 marker 块（%d 字节）"
                  % (kind, len(BLOCKS[kind])))
            changed.append(kind)
            continue
        shutil.copy2(path, path + ".triz-gate.bak")
        io.open(path, "w", encoding="utf-8").write(new_txt)
        print("  ✅ %-14s 已注入（备份 %s.triz-gate.bak）" % (kind, path))
        changed.append(kind)

    # 宿主缺陷修复块**最后**注入（必须在门禁块之后：反序会让门禁块的
    # fallback 锚点匹配到修复块内部，把门禁块插进修复块中间）。
    # 独立函数：即使门禁块阶段失败也不会被跳过——
    # 门禁块缺失只影响「门禁是否生效」，宿主缺陷影响「推送结果是否被
    # 正确判定」，后者更危险，绝不能因前者失败而一起跳过。
    rc_hf, changed_hf = install_hostfix(host_root, dry_run=dry_run)
    changed.extend(changed_hf)
    return (gate_rc or rc_hf), changed



