#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
install_gate_hooks.py — 宿主门禁接入的**可移植安装器**（CYCLE-1 第6轮 · S-E70/S-E71）
=====================================================================================
问题（C1 诊断实测）：
  第5轮 S-E62 把 `self_gate.py` 挂进了两个**宿主文件**：
    ~/.workbuddy/git-hooks/pre-commit · ~/.workbuddy/bin/release-sync.sh
  但这两个文件**不在本仓库内**——干净 `git clone . /tmp/fresh-clone` 后
  `grep -rln "git-hooks/pre-commit|release-sync"` 零命中，
  既无安装器、无快照、也无安装指引。换机/重装/新同事 clone →
  门禁链退回 3 gate，`boundary_guard` 与 9 个判别力自测重新变成幽灵执行点。
  更糟的是 `self_gate.py --self-test` 在该 clone 里仍报「✅ 自测全通过」
  ——它只校验仓库内清单，从不检查「自己是否会被调用」（S-E71 假绿）。

本脚本把宿主接入逻辑**版本化进仓库**：
  - 内置两个代码块（marker 包裹）= 唯一真源；宿主文件里的是派生副本
  - `--verify` 只读检查接入状态 + 内容漂移（供 self_gate 自测消费）
  - `--install` 幂等注入（已有块则跳过；不破坏宿主其余内容；注入前备份）
  - `--self-test` 在临时目录模拟新机器，验证 verifier 有判别力

设计原则：
  - 原则① 散文条款脚本化：宿主接入不再靠「文档里说要配」
  - 原则③ 单源化：判据 `verify_host()` 只此一份，self_gate.py 反向 import
  - 原则④ 禁止幽灵验证项：marker 内容漂移也必须被检出
  - 不硬编码绝对路径：`--host-root` 可参数化，默认 ~/.workbuddy

用法：
  python3 scripts/install_gate_hooks.py --verify
  python3 scripts/install_gate_hooks.py --install
  python3 scripts/install_gate_hooks.py --verify --host-root /tmp/fake-home/.workbuddy
  python3 scripts/install_gate_hooks.py --self-test

退出码：0=正常/已接入  1=未接入或漂移  2=用法/环境错误
"""
import argparse
import io
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)

# ── 宿主文件相对位置（相对 host-root，可参数化）─────────────────────
HOST_FILES = {
    "pre-commit": os.path.join("git-hooks", "pre-commit"),
    "release-sync": os.path.join("bin", "release-sync.sh"),
}

MARK_BEGIN = "# >>> triz-gate BEGIN (generated by scripts/install_gate_hooks.py; DO NOT EDIT) <<<"
MARK_END = "# >>> triz-gate END <<<"

# ── 注入块（唯一真源）──────────────────────────────────────────────
# 与第5轮手工写入宿主文件的逻辑等价；条件式：仅自带 self_gate.py 的包生效。
BLOCK_PRE_COMMIT = """{begin}
# 判别力门禁汇总（由 install_gate_hooks.py 生成；仅自带 self_gate.py 的包生效）
if [ -f "$ROOT/scripts/self_gate.py" ]; then
  if ! OUT=$(cd "$ROOT" && python3 scripts/self_gate.py 2>&1); then
    echo "❌ [pre-commit] 判别力门禁汇总未通过（改坏真源或基线越界）："
    echo "$OUT" | tail -14
    FAIL=1
  fi
fi
{end}
""".format(begin=MARK_BEGIN, end=MARK_END)

BLOCK_RELEASE_SYNC = """{begin}
  # 判别力门禁汇总（由 install_gate_hooks.py 生成；仅自带 self_gate.py 的包生效）
  if [[ -f "$dir/scripts/self_gate.py" ]]; then
    ran=$((ran+1))
    if python3 "$dir/scripts/self_gate.py" >/tmp/.gate_self.log 2>&1; then
      echo "  ✅ gate: self_gate 判别力门禁汇总"
      log "$pkg GATE self_gate=pass"
    else
      echo "  ❌ gate: self_gate 未通过（真源被改坏或基线越界）："
      sed 's/^/       /' /tmp/.gate_self.log | tail -14
      log "$pkg GATE self_gate=FAIL"
      failed=$((failed+1))
    fi
  fi
{end}
""".format(begin=MARK_BEGIN, end=MARK_END)

BLOCKS = {"pre-commit": BLOCK_PRE_COMMIT, "release-sync": BLOCK_RELEASE_SYNC}

# 注入锚点：插到这一行**之前**。找不到锚点 → fail loud，绝不乱插。
ANCHORS = {
    "pre-commit": '# ③ 装配链冒烟',
    "release-sync": '  if [[ $ran -eq 0 ]]; then',
}

# 无锚点时的 fallback（真·新机器：宿主文件是精简版或刚装好的默认版）。
# 按**从后往前**找最后一个稳定结构点插入，保证块落在函数/主体作用域内，
# 且在 `exit`/`return` 之前真正被执行到。找不到任一 → 仍 fail loud。
FALLBACK_ANCHORS = {
    "pre-commit": ['if [ "$FAIL" -ne 0 ]; then', 'exit 0'],
    "release-sync": ['  if [[ $ran -eq 0 ]]; then',
                     '  if [[ $failed -gt 0 ]]; then',
                     '  return 0', '}'],
}

# 兼容第5轮**手写块**（无 marker）：视作已接入，但 verify 会标 legacy。
LEGACY_MARKERS = {
    "pre-commit": '判别力门禁汇总（CYCLE-1 第5轮',
    "release-sync": '# 4) 判别力门禁汇总（CYCLE-1 第5轮',
}


def host_paths(host_root):
    return {k: os.path.join(host_root, v) for k, v in HOST_FILES.items()}


def check_one(kind, path):
    """检查单个宿主文件。返回 dict(status, detail)。

    status ∈ {"installed", "legacy", "drifted", "missing_host_file", "missing"}
    """
    if not os.path.isfile(path):
        return {"status": "missing_host_file", "detail": "宿主文件不存在：%s" % path}
    txt = io.open(path, encoding="utf-8").read()
    expected = BLOCKS[kind]

    if MARK_BEGIN in txt and MARK_END in txt:
        # 从 MARK_BEGIN **所在行的行首**截取（保留首行可能存在的前导缩进）
        mark_pos = txt.index(MARK_BEGIN)
        begin = txt.rfind("\n", 0, mark_pos) + 1
        end = txt.index(MARK_END) + len(MARK_END)
        actual_block = txt[begin:end]
        # 规范化：仅去行尾空白 + 首尾空行（宿主可能被编辑器改过行尾）。
        # 不做「共同缩进剥离」——真源块自带函数体内缩进，剥掉会掩盖
        # 双层缩进等真实漂移。
        def norm(s):
            return "\n".join(x.rstrip() for x in s.strip().splitlines())
        if norm(actual_block) == norm(expected):
            return {"status": "installed", "detail": "marker 块与真源一致"}
        return {"status": "drifted",
                "detail": "marker 块内容漂移（宿主被手改或真源已升级），需 --install 重装"}

    if LEGACY_MARKERS[kind] in txt and "self_gate.py" in txt:
        return {"status": "legacy",
                "detail": "第5轮手写块（无 marker）——功能等价，建议 --install 迁移为可校验形态"}

    if "self_gate.py" in txt:
        return {"status": "legacy",
                "detail": "检测到未识别形态的 self_gate 调用，建议 --install 归一"}

    return {"status": "missing", "detail": "未接入 self_gate"}


def verify_host(host_root, verbose=False):
    """宿主接入状态唯一判据（self_gate.py 反向 import 本函数）。

    返回 (ok: bool, results: dict)。
    legacy 视作**已接入**（功能等价），drifted / missing 判失败。
    """
    results = {k: check_one(k, p) for k, p in host_paths(host_root).items()}
    bad = {k: v for k, v in results.items()
           if v["status"] in ("missing", "missing_host_file", "drifted")}
    if verbose:
        for k, v in sorted(results.items()):
            flag = {"installed": "✅", "legacy": "✅", "drifted": "❌",
                    "missing": "❌", "missing_host_file": "❌"}[v["status"]]
            print("  %s %-14s %-12s %s" % (flag, k, v["status"], v["detail"]))
    return (not bad), results


def install_host(host_root, dry_run=False):
    """幂等注入。已是 installed 则跳过；legacy/missing 则归一为 marker 块。"""
    paths = host_paths(host_root)
    changed = []
    for kind, path in paths.items():
        if not os.path.isfile(path):
            print("  ❌ %-14s 宿主文件不存在，拒绝创建（避免破坏宿主工具链）：%s"
                  % (kind, path))
            return 2, changed
        st = check_one(kind, path)
        if st["status"] == "installed":
            print("  ✅ %-14s 已是最新 marker 块，跳过" % kind)
            continue
        txt = io.open(path, encoding="utf-8").read()

        # 移除旧块（legacy 手写块 or 漂移的 marker 块），再统一注入
        if st["status"] == "drifted":
            b, e = txt.index(MARK_BEGIN), txt.index(MARK_END) + len(MARK_END)
            txt = txt[:b].rstrip() + "\n\n" + txt[e:].lstrip("\n")
        elif st["status"] == "legacy" and LEGACY_MARKERS[kind] in txt:
            # 第5轮手写块：定位注释起点到其 if 块结束。
            # 用「锚点之前」的边界法：手写块总是紧贴 ANCHORS[kind] 之前。
            anchor = ANCHORS[kind]
            if anchor in txt:
                head = txt[:txt.index(anchor)]
                marker_idx = head.find(LEGACY_MARKERS[kind])
                if marker_idx != -1:
                    # 回退到注释块起点（该行首）
                    line_start = head.rfind("\n", 0, marker_idx) + 1
                    txt = head[:line_start] + txt[txt.index(anchor):]
        anchor = ANCHORS[kind] if ANCHORS[kind] in txt else None
        if anchor is None:
            for cand in FALLBACK_ANCHORS[kind]:
                if cand in txt:
                    anchor = cand
                    break
        if anchor is None:
            print("  ❌ %-14s 主锚点与 fallback 锚点均缺失，拒绝盲插" % kind)
            print("     请把宿主文件的结构点补入 ANCHORS/FALLBACK_ANCHORS 后重试")
            return 2, changed
        # 直接注入真源块，**不做缩进再对齐**：BLOCK_RELEASE_SYNC 自带 2 空格
        # 函数体内缩进，若再按锚点缩进叠加一层会造成双重缩进 → check_one
        # 误判 drifted（实测自测暴露）。bash 不在意块级缩进，原样注入最稳。
        block = BLOCKS[kind]
        new_txt = txt.replace(anchor, block + "\n" + anchor, 1)
        if dry_run:
            print("  🔍 %-14s [dry-run] 将注入 marker 块（%d 字节）"
                  % (kind, len(BLOCKS[kind])))
            changed.append(kind)
            continue
        shutil.copy2(path, path + ".triz-gate.bak")
        io.open(path, "w", encoding="utf-8").write(new_txt)
        print("  ✅ %-14s 已注入（备份 %s.triz-gate.bak）" % (kind, path))
        changed.append(kind)
    return 0, changed


def self_test():
    """判别力自测：在临时目录模拟「新机器」，验证 verifier 真能区分接入状态。"""
    import tempfile
    import subprocess
    fails = []
    print("🧪 install_gate_hooks 判别力自测\n")
    with tempfile.TemporaryDirectory() as td:
        root = os.path.join(td, ".workbuddy")
        os.makedirs(os.path.join(root, "git-hooks"))
        os.makedirs(os.path.join(root, "bin"))
        # 构造两个**最小但语法完整**的宿主文件（未接入）
        pc = os.path.join(root, "git-hooks", "pre-commit")
        rs = os.path.join(root, "bin", "release-sync.sh")
        io.open(pc, "w", encoding="utf-8").write(
            '#!/bin/bash\nset -u\nFAIL=0\n# ③ 装配链冒烟\n'
            'if [ "$FAIL" -ne 0 ]; then exit 1; fi\nexit 0\n')
        io.open(rs, "w", encoding="utf-8").write(
            '#!/bin/bash\nrun_gates() {\n  local ran=0 failed=0\n'
            '  if [[ $ran -eq 0 ]]; then return 0; fi\n'
            '  if [[ $failed -gt 0 ]]; then return 1; fi\n'
            '  return 0\n}\n')

        def probe(label, expect_ok):
            ok, res = verify_host(root)
            passed = (ok == expect_ok)
            print("  %s %-40s 期望ok=%-5s 实得ok=%-5s %s"
                  % ("✅" if passed else "❌", label, expect_ok, ok,
                     {k: v["status"] for k, v in res.items()}))
            if not passed:
                fails.append(label)

        probe("新机器（宿主文件存在但未接入）→ 必须判未接入", False)
        rc, _ = install_host(root)
        if rc != 0:
            print("  ❌ install 返回 RC=%d" % rc); fails.append("install rc")
        probe("install 后 → 必须判已接入", True)
        # 幂等：再装一次，marker 不应重复
        rc, changed = install_host(root)
        for path in (pc, rs):
            txt = io.open(path, encoding="utf-8").read()
            if txt.count(MARK_BEGIN) != 1 or txt.count(MARK_END) != 1:
                print("  ❌ 幂等失败：marker 重复 (%s)" % path)
                fails.append("幂等")
        if changed:
            print("  ❌ 幂等失败：第二次 install 仍报告改动 %s" % changed)
            fails.append("幂等改动")
        if not fails:
            print("  ✅ 幂等：二次 install 零改动，marker 各 1 个")

        # 漂移检出：手改 marker 块 → verifier 必须报错
        txt = io.open(pc, encoding="utf-8").read().replace(
            'python3 scripts/self_gate.py 2>&1',
            'python3 scripts/self_gate.py --disabled 2>&1', 1)
        io.open(pc, "w", encoding="utf-8").write(txt)
        probe("marker 块被手改 → 必须判漂移", False)

        # 元判别力：故意写错期望，验证 probe 自身未被短路
        ok_now, _ = verify_host(root)
        meta_ok = (ok_now == "SENTINEL_IMPOSSIBLE")
        if meta_ok:
            print("  ❌ 自测元判别力失效（故意写错的期望被判通过）")
            fails.append("元判别力")
        else:
            print("  ✅ 自测元判别力：故意写错的期望被正确识别为不匹配")

        # 宿主语法未被破坏
        for p in (pc, rs):
            r = subprocess.run(["bash", "-n", p], capture_output=True, text=True)
            if r.returncode != 0:
                print("  ❌ 宿主文件语法被破坏 %s: %s" % (p, r.stderr[:80]))
                fails.append("语法")
        if not any("语法" in f for f in fails):
            print("  ✅ 宿主文件 bash -n 语法完好")

    if fails:
        print("\n❌ 自测失败 %d 项：%s" % (len(fails), fails))
        return 1
    print("\n✅ 自测全通过（接入/漂移/幂等/元判别力/宿主语法）")
    return 0


def main():
    ap = argparse.ArgumentParser(description="宿主门禁接入安装器（S-E70/S-E71）")
    ap.add_argument("--verify", action="store_true", help="只读检查接入状态与漂移")
    ap.add_argument("--install", action="store_true", help="幂等注入（自动备份）")
    ap.add_argument("--dry-run", action="store_true", help="配合 --install 只预览")
    ap.add_argument("--self-test", action="store_true", help="判别力自测")
    ap.add_argument("--host-root", default=os.path.expanduser("~/.workbuddy"),
                    help="宿主根目录（默认 ~/.workbuddy）")
    args = ap.parse_args()

    if args.self_test:
        return self_test()
    if args.verify == args.install:  # 都传或都不传
        ap.print_help()
        return 2

    if args.verify:
        ok, _ = verify_host(args.host_root, verbose=True)
        print("\n结论：%s" % ("✅ 宿主门禁已接入" if ok else "❌ 宿主门禁未接入/漂移"))
        return 0 if ok else 1

    print("🔧 宿主门禁接入 — root=%s%s" %
          (args.host_root, " [dry-run]" if args.dry_run else ""))
    rc, _ = install_host(args.host_root, args.dry_run)
    if rc == 0:
        ok, _ = verify_host(args.host_root, verbose=True)
        if not ok and not args.dry_run:
            print("❌ 注入后校验仍失败", file=sys.stderr)
            return 1
        print("\n结论：%s" % ("✅ 已接入" if ok else "🔍 dry-run 预览完成"))
    return rc


if __name__ == "__main__":
    sys.exit(main())
